-- Yearly location totals keep the analysis responsive on large monthly imports.
-- Remove the superseded monthly aggregate if the earlier migration was already applied.
drop function if exists public.retailer_region_monthly_years(text[], text, text);
drop trigger if exists trigger_sync_retailer_region_monthly on public.retailer_monthly;
drop function if exists public.sync_retailer_region_monthly();
drop table if exists public.retailer_region_monthly;

create table if not exists public.retailer_region_yearly (
  id bigint generated by default as identity primary key,
  branch text not null,
  zone text not null default '',
  year integer not null,
  ga_cnt numeric not null default 0,
  port_in numeric not null default 0,
  port_out numeric not null default 0,
  add_gara numeric not null default 0,
  incentive numeric not null default 0,
  postcode text not null default '',
  city text not null default '',
  province text not null default '',
  region text not null default '',
  source_row_count integer not null default 0,
  unique (branch, zone, year, postcode, city, province, region)
);

create index if not exists retailer_region_yearly_branch_year_idx
  on public.retailer_region_yearly(branch, year);
create index if not exists retailer_region_yearly_zone_year_idx
  on public.retailer_region_yearly(branch, zone, year);
create index if not exists retailer_region_yearly_year_idx
  on public.retailer_region_yearly(year);

insert into public.retailer_region_yearly (
  branch, zone, year, ga_cnt, port_in, port_out, add_gara, incentive,
  postcode, city, province, region, source_row_count
)
select
  rm.branch,
  coalesce(rm.zone, ''),
  coalesce(nullif(substring(rm.month from '^[0-9]{4}'), '')::integer, 0),
  sum(coalesce(rm.ga_cnt, 0)),
  sum(coalesce(rm.port_in, 0)),
  sum(coalesce(rm.port_out, 0)),
  sum(coalesce(rm.add_gara, 0)),
  sum(coalesce(rm.incentive, 0)),
  coalesce(rm.postcode, ''),
  coalesce(rm.city, ''),
  coalesce(rm.province, ''),
  coalesce(rm.region, ''),
  count(*)
from public.retailer_monthly rm
group by rm.branch, coalesce(rm.zone, ''),
         coalesce(nullif(substring(rm.month from '^[0-9]{4}'), '')::integer, 0),
         coalesce(rm.postcode, ''), coalesce(rm.city, ''),
         coalesce(rm.province, ''), coalesce(rm.region, '')
on conflict (branch, zone, year, postcode, city, province, region) do update set
  ga_cnt = excluded.ga_cnt,
  port_in = excluded.port_in,
  port_out = excluded.port_out,
  add_gara = excluded.add_gara,
  incentive = excluded.incentive,
  source_row_count = excluded.source_row_count;

create or replace function public.sync_retailer_region_yearly()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old_year integer;
  v_new_year integer;
begin
  if tg_op in ('UPDATE', 'DELETE') then
    v_old_year := coalesce(nullif(substring(old.month from '^[0-9]{4}'), '')::integer, 0);
    update public.retailer_region_yearly
       set source_row_count = source_row_count - 1,
           ga_cnt = ga_cnt - coalesce(old.ga_cnt, 0),
           port_in = port_in - coalesce(old.port_in, 0),
           port_out = port_out - coalesce(old.port_out, 0),
           add_gara = add_gara - coalesce(old.add_gara, 0),
           incentive = incentive - coalesce(old.incentive, 0)
     where branch = old.branch
       and zone = coalesce(old.zone, '')
       and year = v_old_year
       and postcode = coalesce(old.postcode, '')
       and city = coalesce(old.city, '')
       and province = coalesce(old.province, '')
       and region = coalesce(old.region, '');

    delete from public.retailer_region_yearly
     where branch = old.branch
       and zone = coalesce(old.zone, '')
       and year = v_old_year
       and postcode = coalesce(old.postcode, '')
       and city = coalesce(old.city, '')
       and province = coalesce(old.province, '')
       and region = coalesce(old.region, '')
       and source_row_count <= 0;
  end if;

  if tg_op in ('INSERT', 'UPDATE') then
    v_new_year := coalesce(nullif(substring(new.month from '^[0-9]{4}'), '')::integer, 0);
    insert into public.retailer_region_yearly (
      branch, zone, year, ga_cnt, port_in, port_out, add_gara,
      incentive, postcode, city, province, region, source_row_count
    ) values (
      new.branch, coalesce(new.zone, ''), v_new_year,
      coalesce(new.ga_cnt, 0), coalesce(new.port_in, 0),
      coalesce(new.port_out, 0), coalesce(new.add_gara, 0),
      coalesce(new.incentive, 0), coalesce(new.postcode, ''),
      coalesce(new.city, ''), coalesce(new.province, ''),
      coalesce(new.region, ''), 1
    )
    on conflict (branch, zone, year, postcode, city, province, region) do update set
      ga_cnt = public.retailer_region_yearly.ga_cnt + excluded.ga_cnt,
      port_in = public.retailer_region_yearly.port_in + excluded.port_in,
      port_out = public.retailer_region_yearly.port_out + excluded.port_out,
      add_gara = public.retailer_region_yearly.add_gara + excluded.add_gara,
      incentive = public.retailer_region_yearly.incentive + excluded.incentive,
      source_row_count = public.retailer_region_yearly.source_row_count + 1;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

drop trigger if exists trigger_sync_retailer_region_yearly on public.retailer_monthly;
create trigger trigger_sync_retailer_region_yearly
  after insert or update or delete on public.retailer_monthly
  for each row execute function public.sync_retailer_region_yearly();

alter table public.retailer_region_yearly enable row level security;
