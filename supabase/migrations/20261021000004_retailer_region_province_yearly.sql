grant select on public.retailer_region_province_yearly to authenticated;

drop policy if exists retailer_region_province_yearly_scoped_read on public.retailer_region_province_yearly;
create policy retailer_region_province_yearly_scoped_read
  on public.retailer_region_province_yearly
  for select to authenticated
  using (
    public.has_tool_access('field_iq')
    and public.can_see_branch(branch)
    and (
      public.current_canonical_role() <> 'ZONE-MANAGER'
      or zone = coalesce(public.current_user_zone(), '')
    )
  );

create or replace function public.retailer_region_years(
  p_branches text[] default null,
  p_branch text default null,
  p_zone text default null
)
returns table(year integer)
language sql
stable
security invoker
set search_path = public
as $$
  select distinct sales.year
    from public.retailer_region_province_yearly sales
   where (p_branches is null or sales.branch = any(p_branches))
     and (p_branch is null or sales.branch = p_branch)
     and (p_zone is null or sales.zone = p_zone)
   order by sales.year desc;
$$;

revoke all on function public.retailer_region_years(text[], text, text) from public, anon;
grant execute on function public.retailer_region_years(text[], text, text) to authenticated;

create or replace function public.retailer_region_province_report(
  p_year integer,
  p_branches text[] default null,
  p_branch text default null,
  p_zone text default null
)
returns table(
  province text,
  region text,
  ga_cnt numeric,
  port_in numeric,
  port_out numeric,
  add_gara numeric,
  incentive numeric
)
language sql
stable
security invoker
set search_path = public
as $$
  select sales.province,
         sales.region,
         sum(sales.ga_cnt),
         sum(sales.port_in),
         sum(sales.port_out),
         sum(sales.add_gara),
         sum(sales.incentive)
    from public.retailer_region_province_yearly sales
   where sales.year = p_year
     and (p_branches is null or sales.branch = any(p_branches))
     and (p_branch is null or sales.branch = p_branch)
     and (p_zone is null or sales.zone = p_zone)
   group by sales.province, sales.region
   order by sum(sales.ga_cnt) desc, sales.province;
$$;

revoke all on function public.retailer_region_province_report(integer, text[], text, text) from public, anon;
grant execute on function public.retailer_region_province_report(integer, text[], text, text) to authenticated;
