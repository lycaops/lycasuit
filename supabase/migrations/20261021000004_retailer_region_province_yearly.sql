-- Keep default all-Italy and regional analysis at province granularity.
create table if not exists public.retailer_region_province_yearly (
  id bigint generated by default as identity primary key,
  branch text not null,
  zone text not null default '',
  year integer not null,
  ga_cnt numeric not null default 0,
  port_in numeric not null default 0,
  port_out numeric not null default 0,
  add_gara numeric not null default 0,
  incentive numeric not null default 0,
  province text not null default '',
  region text not null default '',
  source_row_count integer not null default 0,
  unique (branch, zone, year, province, region)
);

create index if not exists retailer_region_province_yearly_year_branch_idx
  on public.retailer_region_province_yearly(year, branch);
create index if not exists retailer_region_province_yearly_branch_zone_year_idx
  on public.retailer_region_province_yearly(branch, zone, year);
create index if not exists retailer_region_province_yearly_province_idx
  on public.retailer_region_province_yearly(province, year);
create index if not exists retailer_region_province_yearly_year_idx
  on public.retailer_region_province_yearly(year);
create index if not exists retailer_region_yearly_province_detail_idx
  on public.retailer_region_yearly(year, province, branch, zone);

insert into public.retailer_region_province_yearly (
  branch, zone, year, ga_cnt, port_in, port_out, add_gara, incentive,
  province, region, source_row_count
)
select
  branch,
  zone,
  year,
  sum(ga_cnt),
  sum(port_in),
  sum(port_out),
  sum(add_gara),
  sum(incentive),
  province,
  region,
  sum(source_row_count)
from public.retailer_region_yearly
group by branch, zone, year, province, region
on conflict (branch, zone, year, province, region) do update set
  ga_cnt = excluded.ga_cnt,
  port_in = excluded.port_in,
  port_out = excluded.port_out,
  add_gara = excluded.add_gara,
  incentive = excluded.incentive,
  source_row_count = excluded.source_row_count;

create or replace function public.sync_retailer_region_province_yearly()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old_year integer;
  v_new_year integer;
begin
  if tg_op in ('UPDATE', 'DELETE') then
    v_old_year := coalesce(nullif(substring(old.month from '^[0-9]{4}'), '')::integer, 0);
    update public.retailer_region_province_yearly
       set source_row_count = source_row_count - 1,
           ga_cnt = ga_cnt - coalesce(old.ga_cnt, 0),
           port_in = port_in - coalesce(old.port_in, 0),
           port_out = port_out - coalesce(old.port_out, 0),
           add_gara = add_gara - coalesce(old.add_gara, 0),
           incentive = incentive - coalesce(old.incentive, 0)
     where branch = old.branch
       and zone = coalesce(old.zone, '')
       and year = v_old_year
       and province = coalesce(old.province, '')
       and region = coalesce(old.region, '');

    delete from public.retailer_region_province_yearly
     where branch = old.branch
       and zone = coalesce(old.zone, '')
       and year = v_old_year
       and province = coalesce(old.province, '')
       and region = coalesce(old.region, '')
       and source_row_count <= 0;
  end if;

  if tg_op in ('INSERT', 'UPDATE') then
    v_new_year := coalesce(nullif(substring(new.month from '^[0-9]{4}'), '')::integer, 0);
    insert into public.retailer_region_province_yearly (
      branch, zone, year, ga_cnt, port_in, port_out, add_gara,
      incentive, province, region, source_row_count
    ) values (
      new.branch, coalesce(new.zone, ''), v_new_year,
      coalesce(new.ga_cnt, 0), coalesce(new.port_in, 0),
      coalesce(new.port_out, 0), coalesce(new.add_gara, 0),
      coalesce(new.incentive, 0), coalesce(new.province, ''),
      coalesce(new.region, ''), 1
    )
    on conflict (branch, zone, year, province, region) do update set
      ga_cnt = public.retailer_region_province_yearly.ga_cnt + excluded.ga_cnt,
      port_in = public.retailer_region_province_yearly.port_in + excluded.port_in,
      port_out = public.retailer_region_province_yearly.port_out + excluded.port_out,
      add_gara = public.retailer_region_province_yearly.add_gara + excluded.add_gara,
      incentive = public.retailer_region_province_yearly.incentive + excluded.incentive,
      source_row_count = public.retailer_region_province_yearly.source_row_count + 1;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

drop trigger if exists trigger_sync_retailer_region_province_yearly on public.retailer_monthly;
create trigger trigger_sync_retailer_region_province_yearly
  after insert or update or delete on public.retailer_monthly
  for each row execute function public.sync_retailer_region_province_yearly();

