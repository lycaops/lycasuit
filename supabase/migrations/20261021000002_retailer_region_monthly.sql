create policy retailer_region_monthly_scoped_read
  on public.retailer_region_monthly
  for select to authenticated
  using (
    public.has_tool_access('field_iq')
    and public.can_see_branch(branch)
    and (
      public.current_canonical_role() <> 'ZONE-MANAGER'
      or zone = coalesce(public.current_user_zone(), '')
    )
  );

create or replace function public.retailer_region_monthly_years(
  p_branches text[] default null,
  p_branch text default null,
  p_zone text default null
)
returns table(year integer)
language sql
stable
security invoker
set search_path = public
as $$
  select distinct sales.year
    from public.retailer_region_monthly sales
   where (p_branches is null or sales.branch = any(p_branches))
     and (p_branch is null or sales.branch = p_branch)
     and (p_zone is null or sales.zone = p_zone)
   order by sales.year desc;
$$;

revoke all on function public.retailer_region_monthly_years(text[], text, text) from public, anon;
grant execute on function public.retailer_region_monthly_years(text[], text, text) to authenticated;
