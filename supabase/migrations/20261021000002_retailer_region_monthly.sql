-- Location dimensions are also retained on the source rows so new monthly
-- imports can populate the regional analysis without changing existing reads.
alter table public.retailer_monthly
  add column if not exists postcode text not null default '',
  add column if not exists city text not null default '',
  add column if not exists province text not null default '',
  add column if not exists region text not null default '';

create table if not exists public.retailer_region_monthly (
  id bigint generated by default as identity primary key,
  branch text not null,
  zone text not null default '',
  month text not null,
  year integer not null,
  ga_cnt numeric not null default 0,
  port_in numeric not null default 0,
  port_out numeric not null default 0,
  add_gara numeric not null default 0,
  incentive numeric not null default 0,
  postcode text not null default '',
  city text not null default '',
  province text not null default '',
  region text not null default '',
  retailer_count integer not null default 0,
  unique (branch, zone, month, postcode, city, province, region)
);

create index if not exists retailer_region_monthly_scope_idx
  on public.retailer_region_monthly(branch, zone, year);
create index if not exists retailer_region_monthly_province_idx
  on public.retailer_region_monthly(province);
create index if not exists retailer_region_monthly_city_idx
  on public.retailer_region_monthly(city);

insert into public.retailer_region_monthly (
  branch, zone, month, year, ga_cnt, port_in, port_out, add_gara, incentive,
  postcode, city, province, region, retailer_count
)
select
  rm.branch,
  coalesce(rm.zone, ''),
  rm.month,
  coalesce(nullif(substring(rm.month from '^[0-9]{4}'), '')::integer, 0),
  sum(coalesce(rm.ga_cnt, 0)),
  sum(coalesce(rm.port_in, 0)),
  sum(coalesce(rm.port_out, 0)),
  sum(coalesce(rm.add_gara, 0)),
  sum(coalesce(rm.incentive, 0)),
  coalesce(rm.postcode, ''),
  coalesce(rm.city, ''),
  coalesce(rm.province, ''),
  coalesce(rm.region, ''),
  count(*)
from public.retailer_monthly rm
group by rm.branch, coalesce(rm.zone, ''), rm.month, coalesce(rm.postcode, ''),
         coalesce(rm.city, ''), coalesce(rm.province, ''), coalesce(rm.region, '')
on conflict (branch, zone, month, postcode, city, province, region) do update set
  year = excluded.year,
  ga_cnt = excluded.ga_cnt,
  port_in = excluded.port_in,
  port_out = excluded.port_out,
  add_gara = excluded.add_gara,
  incentive = excluded.incentive,
  retailer_count = excluded.retailer_count;

create or replace function public.sync_retailer_region_monthly()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_branch text;
  v_zone text;
  v_month text;
  v_postcode text;
  v_city text;
  v_province text;
  v_region text;
  v_year integer;
begin
  if tg_op in ('UPDATE', 'DELETE') then
    v_branch := old.branch;
    v_zone := coalesce(old.zone, '');
    v_month := old.month;
    v_postcode := coalesce(old.postcode, '');
    v_city := coalesce(old.city, '');
    v_province := coalesce(old.province, '');
    v_region := coalesce(old.region, '');
    v_year := coalesce(nullif(substring(old.month from '^[0-9]{4}'), '')::integer, 0);

    update public.retailer_region_monthly
       set retailer_count = retailer_count - 1,
           ga_cnt = ga_cnt - coalesce(old.ga_cnt, 0),
           port_in = port_in - coalesce(old.port_in, 0),
           port_out = port_out - coalesce(old.port_out, 0),
           add_gara = add_gara - coalesce(old.add_gara, 0),
           incentive = incentive - coalesce(old.incentive, 0)
     where branch = v_branch and zone = v_zone and month = v_month
       and postcode = v_postcode and city = v_city
       and province = v_province and region = v_region;

    delete from public.retailer_region_monthly
     where branch = v_branch and zone = v_zone and month = v_month
       and postcode = v_postcode and city = v_city
       and province = v_province and region = v_region
       and retailer_count <= 0;
  end if;

  if tg_op in ('INSERT', 'UPDATE') then
    v_year := coalesce(nullif(substring(new.month from '^[0-9]{4}'), '')::integer, 0);
    insert into public.retailer_region_monthly (
      branch, zone, month, year, ga_cnt, port_in, port_out, add_gara,
      incentive, postcode, city, province, region, retailer_count
    ) values (
      new.branch, coalesce(new.zone, ''), new.month, v_year,
      coalesce(new.ga_cnt, 0), coalesce(new.port_in, 0),
      coalesce(new.port_out, 0), coalesce(new.add_gara, 0),
      coalesce(new.incentive, 0), coalesce(new.postcode, ''),
      coalesce(new.city, ''), coalesce(new.province, ''),
      coalesce(new.region, ''), 1
    )
    on conflict (branch, zone, month, postcode, city, province, region) do update set
      year = excluded.year,
      ga_cnt = public.retailer_region_monthly.ga_cnt + excluded.ga_cnt,
      port_in = public.retailer_region_monthly.port_in + excluded.port_in,
      port_out = public.retailer_region_monthly.port_out + excluded.port_out,
      add_gara = public.retailer_region_monthly.add_gara + excluded.add_gara,
      incentive = public.retailer_region_monthly.incentive + excluded.incentive,
      retailer_count = public.retailer_region_monthly.retailer_count + 1;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

drop trigger if exists trigger_sync_retailer_region_monthly on public.retailer_monthly;
create trigger trigger_sync_retailer_region_monthly
  after insert or update or delete on public.retailer_monthly
  for each row execute function public.sync_retailer_region_monthly();

